import os
import sys
from pathlib import Path


def generate_shader_sources(shader_dir: str, output_file: str):
    """Generate a C++ file with shader sources embedded as string literals."""
    sources = {}
    
    shader_path = Path(shader_dir)
    if not shader_path.exists():
        print(f"Error: Shader directory '{shader_dir}' not found")
        sys.exit(1)
    
    for root, _dirs, files in os.walk(shader_path):
        for f in files:
            if Path(f).suffix.lower() == '.glsl':
                full_path = Path(root) / f
                name = Path(f).stem
                with open(full_path, 'r') as sf:
                    sources[name] = sf.read()
    
    with open(output_file, 'w') as out:
        out.write("// Auto-generated by gen_shader_sources.py - DO NOT EDIT\n")
        out.write("// Embedded shader sources\n\n")
        out.write("#include <string>\n\n")
        out.write("namespace shaders {\n\n")
        
        # Map shader filenames to expected function names
        # vertex_shader.glsl -> VertexShaderSource
        # fragment_shader.glsl -> FragmentShaderSource
        type_map = {}
        for fname in sources.keys():
            base = Path(fname).stem.lower()
            if 'vert' in base or base == 'vertex_shader':
                type_map['Vertex'] = fname
            elif 'frag' in base or base == 'fragment_shader':
                type_map['Fragment'] = fname
            elif 'geom' in base:
                type_map['Geometry'] = fname
            elif 'comp' in base:
                type_map['Compute'] = fname
        
        # Generate functions with standard names
        for shader_type in ['Vertex', 'Fragment', 'Geometry', 'Compute']:
            if shader_type in type_map:
                fname = type_map[shader_type]
                func_name = f"{shader_type}ShaderSource"
                out.write(f"inline const char* {func_name}() {{\n")
                out.write(f'    return R"shader(\n')
                out.write(sources[fname])
                out.write(')shader";\n')
                out.write("}\n\n")
        
        out.write("} // namespace shaders\n")
    
    print(f"[Python] Generated shader sources: {output_file}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <shader_dir> <output_file>")
        sys.exit(1)
    generate_shader_sources(sys.argv[1], sys.argv[2])